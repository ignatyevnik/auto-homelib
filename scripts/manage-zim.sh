#!/bin/bash
# ?????? ?????????? ZIM-??????? ????? kiwix-tools

ZIM_PATH="/mnt/hdd1/docker/kiwix"
DOWNLOADS="/mnt/hdd1/downloads"
KIWIX_CONTAINER="homelib-kiwix"

show_help() {
    cat << EOF
?? Kiwix ZIM Manager

?????????????:
    ./manage-zim.sh [???????] [????????]

???????:
    list                    ???????? ??? ZIM-????? ? ??????????
    info <????>             ???????? ?????????? ? ZIM-?????
    download <URL>          ??????? ZIM-???? ?? ?????????
    download-wikipedia      ??????? Wikipedia RU (????????? ??????)
    download-wikihow        ??????? WikiHow RU
    search <??????>         ????? ? ZIM-?????? (????????? kiwix-search)
    restart                 ????????????? Kiwix ????? ?????????? ??????

???????:
    ./manage-zim.sh list
    ./manage-zim.sh info wikipedia_ru_all_maxi.zim
    ./manage-zim.sh download https://download.kiwix.org/zim/wikipedia_ru_all_maxi.zim
    ./manage-zim.sh download-wikipedia

EOF
}

list_zims() {
    echo "?? ZIM-????? ? ??????????:"
    echo "=========================="
    ls -lh "$ZIM_PATH"/*.zim 2>/dev/null | awk '{print $9, "(" $5 ")"}' || echo "? ??? ZIM-??????"
    echo ""
    echo "?? ????? ??????:"
    du -sh "$ZIM_PATH" 2>/dev/null || echo "0"
}

info_zim() {
    local zim_file="$1"
    if [ ! -f "$ZIM_PATH/$zim_file" ]; then
        echo "? ???? ?? ??????: $zim_file"
        return 1
    fi
    docker exec "$KIWIX_CONTAINER" kiwix-manage "$ZIM_PATH/$zim_file" show
}

download_zim() {
    local url="$1"
    local filename=$(basename "$url")
    
    echo "?? ??????????: $filename"
    cd "$DOWNLOADS"
    
    if command -v aria2c &> /dev/null; then
        aria2c -x 4 -s 4 --continue=true "$url"
    else
        wget -c "$url"
    fi
    
    echo "? ???????. ?????????? ? ??????????..."
    mv "$filename" "$ZIM_PATH/"
    echo "?? ?????????? Kiwix..."
    docker restart "$KIWIX_CONTAINER"
    echo "? ??????!"
}

download_wikipedia() {
    echo "?? ?????????? Wikipedia RU..."
    local url="https://download.kiwix.org/zim/wikipedia/wikipedia_ru_all_maxi_2024-01.zim"
    download_zim "$url"
}

download_wikihow() {
    echo "?? ?????????? WikiHow RU..."
    local url="https://download.kiwix.org/zim/wikihow/wikihow_ru_maxi_2024-01.zim"
    download_zim "$url"
}

restart_kiwix() {
    echo "?? ?????????? Kiwix..."
    docker restart "$KIWIX_CONTAINER"
    echo "? ??????!"
}

case "$1" in
    list)
        list_zims
        ;;
    info)
        [ -z "$2" ] && { echo "? ??????? ??? ?????"; exit 1; }
        info_zim "$2"
        ;;
    download)
        [ -z "$2" ] && { echo "? ??????? URL"; exit 1; }
        download_zim "$2"
        ;;
    download-wikipedia)
        download_wikipedia
        ;;
    download-wikihow)
        download_wikihow
        ;;
    search)
        [ -z "$2" ] && { echo "? ??????? ????????? ??????"; exit 1; }
        docker exec "$KIWIX_CONTAINER" kiwix-search /data/*.zim "$2"
        ;;
    restart)
        restart_kiwix
        ;;
    help|--help|-h)
        show_help
        ;;
    *)
        show_help
        ;;
esac