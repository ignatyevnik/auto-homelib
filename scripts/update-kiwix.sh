#!/bin/bash
# ?????? ??? ??????????????? ?????????? XML-?????????? Kiwix

ZIM_PATH="/mnt/hdd1/docker/kiwix"
LIBRARY_XML="$ZIM_PATH/library.xml"
CONTAINER="homelib-kiwix"

echo "?? ?????????? ?????????? Kiwix..."

# ?????????, ??? ????????? ???????
if ! docker ps | grep -q "$CONTAINER"; then
    echo "? ????????? $CONTAINER ?? ???????!"
    exit 1
fi

# ??????? ????????? ????? ?????? ??????????
if [ -f "$LIBRARY_XML" ]; then
    cp "$LIBRARY_XML" "$LIBRARY_XML.bak"
fi

# ??????? ????? ?????????? ? ??????? ??????????
cat > "$LIBRARY_XML" << 'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<library version="20110515">
EOF

# ????? ??? ZIM-????? ? ???????? ?? ? ??????????
ZIM_COUNT=0
for zim in "$ZIM_PATH"/*.zim; do
    if [ -f "$zim" ]; then
        zim_name=$(basename "$zim")
        echo "  ? ??????????: $zim_name"
        docker exec "$CONTAINER" kiwix-manage /data/library.xml add "/data/$zim_name" 2>/dev/null || true
        ZIM_COUNT=$((ZIM_COUNT + 1))
    fi
done

# ??????? XML
echo '</library>' >> "$LIBRARY_XML"

echo "? ????????? ZIM-??????: $ZIM_COUNT"

# ????????????? Kiwix ??? ?????????? ?????????
if [ $ZIM_COUNT -gt 0 ]; then
    echo "?? ?????????? Kiwix..."
    docker restart "$CONTAINER"
    echo "? ??????!"
else
    echo "?? ZIM-????? ?? ??????? ? $ZIM_PATH"
fi

# ???????? ??????? ?????????? ??????????
echo ""
echo "?? ??????? ??????????:"
docker exec "$CONTAINER" kiwix-manage /data/library.xml show 2>/dev/null | grep -E "id|path|title" | head -20